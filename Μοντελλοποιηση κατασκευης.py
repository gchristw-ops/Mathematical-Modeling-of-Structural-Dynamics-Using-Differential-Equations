import numpy as np
from scipy.linalg import solve_banded


# ============================================================
# 1. ΕΙΣΑΓΩΓΗ ΒΑΣΙΚΩΝ ΔΕΔΟΜΕΝΩΝ
# ============================================================

L = float(input("Δώσε το μήκος L του πεδίου ορισμού: "))
k = float(input("Δώσε τη σταθερά ακρίβειας k: "))
n = int(input("Δώσε τον αριθμό n των εξισώσεων: "))
mu = float(input("Δώσε την τάξη μ: "))
nu = float(input("Δώσε την τάξη ν: "))


# ============================================================
# 2. ΥΠΟΛΟΓΙΣΜΟΣ ΤΟΥ N
#
# N_real = 2L(1+2k) / pi
# N = round(N_real)
# ============================================================

N_real = (2 * L * (1 + 2 * k)) / np.pi

N = int(round(N_real))

if N < 1:
    raise ValueError("Το N πρέπει να είναι τουλάχιστον 1.")


print()
print("=" * 60)
print("ΥΠΟΛΟΓΙΣΜΟΣ N")
print("=" * 60)

print("N_real =", N_real)
print("N      =", N)


# ============================================================
# 3. ΥΠΟΛΟΓΙΣΜΟΣ ΤΩΝ ΣΗΜΕΙΩΝ t_j
#
# t_j = j*pi / [2(1+2k)]
#
# j = 1,...,N
# ============================================================

t_values = np.array(
    [
        j * np.pi / (2 * (1 + 2 * k))
        for j in range(1, N + 1)
    ]
)


# ============================================================
# 4. ΣΥΝΑΡΤΗΣΗ Φ_n(t)
# ============================================================

def Phi(n_index, t, k):

    term1 = np.sin(
        (1 + 2 * k)
        * (
            t
            + 2
            * (
                -np.pi / 4
                + (np.pi / 4) * (-1) ** n_index
            )
        )
    ) ** 2

    term2 = np.sin(
        (1 + 2 * k)
        * (
            t
            + 2
            * (
                -np.pi / 4
                + (np.pi / 4) * (-1) ** (n_index + 1)
            )
        )
    ) ** 2

    return term1 + term2


# ============================================================
# 5. ΣΥΝΑΡΤΗΣΗ Φ_n^μ(t)
# ============================================================

def Phi_mu(n_index, t, k, mu):

    term1 = np.cos(
        (2 + 4 * k)
        * (
            t
            + 2
            * (
                -np.pi / 4
                + (np.pi / 4) * (-1) ** n_index
            )
        )
        + mu * np.pi / 2
    )

    term2 = np.cos(
        (2 + 4 * k)
        * (
            t
            + 2
            * (
                -np.pi / 4
                + (np.pi / 4) * (-1) ** (n_index + 1)
            )
        )
        + mu * np.pi / 2
    )

    return (
        -(2 + 4 * k) ** mu
        / 2
        * (term1 + term2)
    )


# ============================================================
# 6. ΣΥΝΑΡΤΗΣΗ Φ_n^ν(t)
# ============================================================

def Phi_nu(n_index, t, k, nu):

    term1 = np.cos(
        (2 + 4 * k)
        * (
            t
            + 2
            * (
                -np.pi / 4
                + (np.pi / 4) * (-1) ** n_index
            )
        )
        + nu * np.pi / 2
    )

    term2 = np.cos(
        (2 + 4 * k)
        * (
            t
            + 2
            * (
                -np.pi / 4
                + (np.pi / 4) * (-1) ** (n_index + 1)
            )
        )
        + nu * np.pi / 2
    )

    return (
        -(2 + 4 * k) ** nu
        / 2
        * (term1 + term2)
    )


# ============================================================
# 7. ΥΠΟΛΟΓΙΣΜΟΣ Φ_j, Φ_j^μ, Φ_j^ν
#
# j = 1,...,N
# ============================================================

Phi_values = np.zeros(N)

Phi_mu_values = np.zeros(N)

Phi_nu_values = np.zeros(N)


for j in range(1, N + 1):

    t = t_values[j - 1]

    Phi_values[j - 1] = Phi(
        j,
        t,
        k
    )

    Phi_mu_values[j - 1] = Phi_mu(
        j,
        t,
        k,
        mu
    )

    Phi_nu_values[j - 1] = Phi_nu(
        j,
        t,
        k,
        nu
    )


# ============================================================
# 8. ΕΙΣΑΓΩΓΗ ΠΙΝΑΚΑ M
# ============================================================

print()
print("=" * 60)
print("ΕΙΣΑΓΩΓΗ ΠΙΝΑΚΑ M")
print("=" * 60)

M = np.zeros((n, n))


for i in range(n):

    for j in range(n):

        M[i, j] = float(
            input(
                f"M[{i + 1},{j + 1}] = "
            )
        )


# ============================================================
# 9. ΕΙΣΑΓΩΓΗ ΠΙΝΑΚΑ c
# ============================================================

print()
print("=" * 60)
print("ΕΙΣΑΓΩΓΗ ΠΙΝΑΚΑ c")
print("=" * 60)

c = np.zeros((n, n))


for i in range(n):

    for j in range(n):

        c[i, j] = float(
            input(
                f"c[{i + 1},{j + 1}] = "
            )
        )


# ============================================================
# 10. ΕΙΣΑΓΩΓΗ ΠΙΝΑΚΑ K
# ============================================================

print()
print("=" * 60)
print("ΕΙΣΑΓΩΓΗ ΠΙΝΑΚΑ K")
print("=" * 60)

K = np.zeros((n, n))


for i in range(n):

    for j in range(n):

        K[i, j] = float(
            input(
                f"K[{i + 1},{j + 1}] = "
            )
        )


# ============================================================
# 11. ΕΙΣΑΓΩΓΗ ΤΩΝ ΣΥΝΑΡΤΗΣΕΩΝ F_i(t)
#
# Ο χρήστης γράφει:
#
#   10*sin(t)
#   5*cos(t)
#   3*exp(-t)
#
# Για δύναμη:
#
#   t**2
#
# ============================================================

print()
print("=" * 60)
print("ΕΙΣΑΓΩΓΗ ΣΥΝΑΡΤΗΣΕΩΝ F_i(t)")
print("=" * 60)

print()
print("Παραδείγματα:")
print("  10*sin(t)")
print("  5*cos(t)")
print("  3*exp(-t)")
print("  t**2")
print("  t**3 + 2*t")
print("  sqrt(t)")
print("  log(t)")
print()

F = []


for i in range(n):

    expression = input(
        f"Δώσε τη συνάρτηση F_{i + 1}(t): "
    )

    # --------------------------------------------------------
    # Έλεγχος της συνάρτησης
    # --------------------------------------------------------

    try:

        eval(
            expression,
            {
                "__builtins__": {},
                "np": np,
                "sin": np.sin,
                "cos": np.cos,
                "tan": np.tan,
                "exp": np.exp,
                "log": np.log,
                "sqrt": np.sqrt,
                "pi": np.pi,
                "abs": np.abs
            },
            {
                "t": 1.0
            }
        )

    except Exception as error:

        raise ValueError(
            f"\nΗ συνάρτηση F_{i + 1}(t) "
            f"δεν είναι έγκυρη.\n"
            f"Έδωσες: {expression}\n"
            f"Σφάλμα: {error}"
        )


    # --------------------------------------------------------
    # Δημιουργία της συνάρτησης
    # --------------------------------------------------------

    def F_i(t, expression=expression):

        return eval(
            expression,
            {
                "__builtins__": {},
                "np": np,
                "sin": np.sin,
                "cos": np.cos,
                "tan": np.tan,
                "exp": np.exp,
                "log": np.log,
                "sqrt": np.sqrt,
                "pi": np.pi,
                "abs": np.abs
            },
            {
                "t": t
            }
        )

    F.append(F_i)


# ============================================================
# 12. ΔΗΜΙΟΥΡΓΙΑ ΤΟΥ ΤΕΛΙΚΟΥ ΠΙΝΑΚΑ
#
# yapproximation : 1 x n
# ============================================================

yapproximation = np.zeros((1, n))


# ============================================================
# 13. ΚΥΡΙΑ ΕΠΑΝΑΛΗΨΗ
#
# Για κάθε i = 1,...,n
# ============================================================

for i in range(n):

    print()
    print("=" * 60)
    print(f"ΕΠΑΝΑΛΗΨΗ i = {i + 1}")
    print("=" * 60)


    # ========================================================
    # 13.1 ΥΠΟΛΟΓΙΣΜΟΣ G^(i)
    #
    # G^(i) =
    # [F_i(t_1), ..., F_i(t_N)]
    # ========================================================

    G = np.zeros(N)


    for j in range(N):

        G[j] = F[i](
            t_values[j]
        )


    # ========================================================
    # 13.2 ΑΘΡΟΙΣΜΑΤΑ ΤΗΣ i-ΟΣΤΗΣ ΓΡΑΜΜΗΣ
    # ========================================================

    sum_M = np.sum(
        M[i, :]
    )

    sum_c = np.sum(
        c[i, :]
    )

    sum_K = np.sum(
        K[i, :]
    )


    # ========================================================
    # 13.3 ΥΠΟΛΟΓΙΣΜΟΣ ymethod
    #
    # ymethod_j =
    #
    # sum_M * Φ_j^μ
    # +
    # sum_c * Φ_j^ν
    # +
    # sum_K * Φ_j
    # ========================================================

    ymethod = np.zeros(N)


    for j in range(N):

        ymethod[j] = (

            sum_M * Phi_mu_values[j]

            + sum_c * Phi_nu_values[j]

            + sum_K * Phi_values[j]

        )


    # ========================================================
    # 13.4 ΥΠΟΛΟΓΙΣΜΟΣ Q
    #
    # Q_j =
    #
    # sum_M * Φ_j^μ
    # +
    # sum_c * Φ_j^ν
    # ========================================================

    Q = np.zeros(N)


    for j in range(N):

        Q[j] = (

            sum_M * Phi_mu_values[j]

            + sum_c * Phi_nu_values[j]

        )


    # ========================================================
    # 13.5 ΚΑΤΑΣΚΕΥΗ ΤΟΥ ΤΡΙΔΙΑΓΩΝΙΟΥ ΠΙΝΑΚΑ T
    #
    # Δεν χρειάζεται να δημιουργήσουμε ολόκληρο τον
    # πίνακα T.
    #
    # Χρειαζόμαστε μόνο:
    #
    #   κάτω διαγώνιο
    #   κύρια διαγώνιο
    #   πάνω διαγώνιο
    #
    # ========================================================

    lower_diagonal = np.zeros(N - 1)

    main_diagonal = ymethod.copy()

    upper_diagonal = np.zeros(N - 1)


    for j in range(N - 1):

        lower_diagonal[j] = Q[j]

        upper_diagonal[j] = Q[j]


    # ========================================================
    # 13.6 ΛΥΣΗ ΓΙΑ U
    #
    # Θέλουμε:
    #
    # U = G T^(-1)
    #
    # Αυτό ισοδυναμεί με:
    #
    # T^T U^T = G^T
    #
    # Επειδή ο T είναι συμμετρικός:
    #
    # T^T = T
    #
    # άρα λύνουμε:
    #
    # T U^T = G^T
    #
    # Χρησιμοποιούμε solve_banded επειδή ο T είναι
    # τριδιαγώνιος.
    #
    # ========================================================

    # Μορφή banded πίνακα για scipy:
    #
    # ab[0, :] -> πάνω διαγώνιος
    # ab[1, :] -> κύρια διαγώνιος
    # ab[2, :] -> κάτω διαγώνιος

    ab = np.zeros(
        (3, N)
    )


    # Κύρια διαγώνιος

    ab[1, :] = main_diagonal


    # Πάνω διαγώνιος

    ab[0, 1:] = upper_diagonal


    # Κάτω διαγώνιος

    ab[2, :-1] = lower_diagonal


    try:

        U = solve_banded(
            (1, 1),
            ab,
            G
        )

    except Exception as error:

        raise ValueError(
            f"\nΑποτυχία επίλυσης του "
            f"τριδιαγώνιου συστήματος "
            f"στην επανάληψη i = {i + 1}.\n"
            f"Σφάλμα: {error}"
        )


    # ========================================================
    # 13.7 ΥΠΟΛΟΓΙΣΜΟΣ ΤΗΣ i-ΟΣΤΗΣ ΠΡΟΣΕΓΓΙΣΗΣ
    #
    # y_i^approx =
    #
    # sum_{j=1}^N Φ_j U_j
    # ========================================================

    y_i = np.sum(
        Phi_values * U
    )


    # Αποθήκευση στο yapproximation

    yapproximation[0, i] = y_i


    print(
        f"y_{i + 1}^approximation = "
        f"{y_i:.12e}"
    )


# ============================================================
# 14. ΤΕΛΙΚΟ ΑΠΟΤΕΛΕΣΜΑ
# ============================================================

print()
print("=" * 60)
print("ΤΕΛΙΚΟ ΑΠΟΤΕΛΕΣΜΑ")
print("=" * 60)

print()
print("yapproximation =")
print(yapproximation)


# ============================================================
# 15. ΔΙΑΣΤΑΣΕΙΣ ΤΕΛΙΚΟΥ ΑΠΟΤΕΛΕΣΜΑΤΟΣ
# ============================================================

print()
print("Διαστάσεις yapproximation:")
print(yapproximation.shape)